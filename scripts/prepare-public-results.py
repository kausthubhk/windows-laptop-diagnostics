#!/usr/bin/env python3
"""Build the reviewed, text-only public evidence set from an explicit source allowlist.

Run from any directory with Python 3. The script never modifies its source evidence.
It writes only under results/ and will overwrite only files generated by this script.
The allowlist is intentionally explicit; new raw files are excluded until reviewed.
"""
from __future__ import annotations

import csv
import argparse
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "results"
MANIFEST = {"schema_version": 1, "generated_utc": None, "files": [], "excluded": []}


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def clean_text(value: str) -> str:
    """Remove local identity/path tokens while retaining benchmark output structure."""
    value = value.replace(str(ROOT), "<REPOSITORY>").replace(str(ROOT).replace("\\", "/"), "<REPOSITORY>")
    value = re.sub(r"(?i)C:\\Users\\[^\\\s,;\"]+", "<USERPROFILE>", value)
    value = re.sub(r"(?i)C:\\(?:[^\s,;\"]+)", "<ABS_PATH>", value)
    value = re.sub(r"(?i)\\\\[A-Z0-9_-]+\\(memory|physicaldisk)\\", r"\\\\HOST\\\1\\", value)
    value = re.sub(r"(?i)(service tag|servicetag|system uuid|system serial|serial number|ppid|product key)\s*[:=]\s*[^\r\n,]+", r"\1: <REDACTED>", value)
    value = re.sub(r"(?i)\b(?:[0-9A-F]{2}:){5}[0-9A-F]{2}\b", "<MAC>", value)
    value = re.sub(r"\b(?:\d{1,3}\.){3}\d{1,3}\b", "<IP>", value)
    return value


def register(src: Path, dst: Path, method: str, *, payload: bytes | None = None, source_label: str | None = None) -> None:
    raw = src.read_bytes()
    data = payload if payload is not None else raw
    # All files are explicitly emitted as UTF-8 text. This catches accidental binary inclusion.
    data.decode("utf-8")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(data)
    try:
        source_name = rel(src)
    except ValueError:
        source_name = source_label or "external-source/<omitted>"
    MANIFEST["files"].append({
        "path": rel(dst), "source": source_name, "source_sha256": hashlib.sha256(raw).hexdigest(),
        "output_sha256": hashlib.sha256(data).hexdigest(), "transform": method,
        "bytes": len(data), "format": dst.suffix.lstrip(".") or "text"
    })


def copy_text(src_rel: str, dst_rel: str, method: str = "allowlisted text copy; local paths and identifiers redacted") -> None:
    src = ROOT / src_rel
    txt = clean_text(src.read_text(encoding="utf-8-sig", errors="replace"))
    register(src, DEST / dst_rel, method, payload=txt.encode("utf-8"))


def filtered_csv(src_rel: str, dst_rel: str, keep: list[str], method: str) -> None:
    src = ROOT / src_rel
    filtered_csv_path(src, src_rel, DEST / dst_rel, keep, method)


def filtered_csv_path(src: Path, source_label: str, dst: Path, keep: list[str], method: str) -> None:
    with src.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        field_map = {x.lower(): x for x in (reader.fieldnames or [])}
        fields = [field_map[x.lower()] for x in keep if x.lower() in field_map]
        if not fields:
            raise ValueError(f"No allowed columns found in {source_label}")
        rows = []
        for row in reader:
            out = {k: row.get(k, "") for k in fields}
            for k, v in out.items():
                if k.lower() in {"path", "counterpath"}:
                    out[k] = re.sub(r"(?i)^\\\\[^\\]+\\", r"\\\\HOST\\", v)
            rows.append(out)
    import io
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
    writer.writeheader(); writer.writerows(rows)
    register(src, dst, method, payload=stream.getvalue().encode("utf-8"), source_label=source_label)


def json_subset(src_rel: str, dst_rel: str, subset: dict, method: str) -> None:
    src = ROOT / src_rel
    register(src, DEST / dst_rel, method, payload=(json.dumps(subset, indent=2, ensure_ascii=False) + "\n").encode())


def hardware_summary(src_rel: str, dst_rel: str, date: str, topology: str) -> None:
    src = ROOT / src_rel
    hardware_summary_path(src, src_rel, DEST / dst_rel, date, topology)


def hardware_summary_path(src: Path, source_label: str, dst: Path, date: str, topology: str) -> None:
    text = src.read_text(encoding="utf-8-sig", errors="replace")
    cpu_match = re.search(r"(?m)^Name\s*:\s*(.+)$", text)
    clock = re.search(r"(?m)^Power Scheme GUID:.*?\(([^)]+)\)", text)
    modules = []
    for line in text.splitlines():
        m = re.match(r"^DIMM\s+\w+\s+\S+\s+(\S+)\s+(\d+)\s+(\d+)\s+(\d+)\s+\d+\s*$", line.strip())
        if m:
            part, capacity, speed, configured = m.groups()
            modules.append({"part_number": part, "capacity_gib": int(capacity) / 1073741824,
                            "reported_speed_mt_s": int(speed), "configured_speed_mt_s": int(configured)})
    # A second table layout has blank manufacturer and no extra separator; parse known part models safely.
    if not modules:
        for part, cap, speed, configured in re.findall(r"(M471A[0-9A-Z-]+)\s+(\d{10,})\s+(\d{4})\s+(\d{4})", text):
            modules.append({"part_number": part, "capacity_gib": int(cap) / 1073741824,
                            "reported_speed_mt_s": int(speed), "configured_speed_mt_s": int(configured)})
    out = {
        "date": date, "system_model": "Dell G3 3500",
        "cpu_model": cpu_match.group(1).strip() if cpu_match else "Intel Core i5-10300H",
        "ram_topology": topology, "modules": modules,
        "power_plan": clock.group(1).strip() if clock else "Balanced",
        "source_scope": "Allowlisted CIM inventory fields only; hostnames, serials, paths, and device identifiers omitted."
    }
    register(src, dst, "generated from allowlisted system/CIM fields; identifiers omitted",
             payload=(json.dumps(out, indent=2) + "\n").encode(), source_label=source_label)


def final_scan(destination: Path) -> dict:
    checks = {"absolute_windows_paths": r"(?i)\b[A-Z]:\\(?:Users|Windows|Program Files)\\",
              "host_counter_names": r"(?i)\\\\(?!HOST\\)[A-Z0-9_-]+\\memory\\",
              "mac_addresses": r"(?i)\b(?:[0-9a-f]{2}:){5}[0-9a-f]{2}\b",
              "ipv4_literals": r"\b(?:\d{1,3}\.){3}\d{1,3}\b",
              "uuid_values": r"(?i)\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b",
              "private_identity_labels": r"(?i)(?:service tag|servicetag|system uuid|serial number|ppid|product key)\s*[:=]\s*\S+"}
    violations = []
    scan_files = [p for p in destination.rglob("*") if p.is_file() and p.name != "manifest.json"]
    for area in (ROOT / "docs", ROOT / "scripts"):
        if area.exists():
            scan_files.extend(p for p in area.rglob("*") if p.is_file() and p.suffix.lower() in {".md", ".py"})
    for output in scan_files:
        if output.suffix.lower() not in {".txt", ".md", ".json", ".csv", ".jsonl", ".py"}:
            violations.append({"path": rel(output) if output.is_relative_to(ROOT) else "external-output", "reason": "non-text format"})
            continue
        sample = output.read_text(encoding="utf-8", errors="replace")
        for name, pattern in checks.items():
            for match in re.finditer(pattern, sample):
                before = sample[max(0, match.start() - 24):match.start()]
                line_start = sample.rfind("\n", 0, match.start()) + 1
                line_end = sample.find("\n", match.end())
                line = sample[line_start:line_end if line_end >= 0 else len(sample)]
                # Do not report dotted software versions as network addresses or vendor URL IDs as personal UUIDs.
                if name == "ipv4_literals" and re.search(r"(?i)(?:version|ver\.?|v|reported)\b[^0-9]{0,12}$", before):
                    continue
                if name == "uuid_values" and re.search(r"(?i)https?://(?:[^/]+\.)?dell\.com/", line):
                    continue
                violations.append({"path": rel(output) if output.is_relative_to(ROOT) else "external-output", "check": name})
                break
    return {"checks": list(checks), "scope": "generated results plus docs/*.md and scripts/*.py",
            "violations": violations, "result": "pass" if not violations else "review required",
            "note": "No matched private values are printed; dotted software versions and Dell documentation URL GUIDs are excluded from network-address/UUID findings; hashes and source paths are relative."}


def export_generic(run_dir: Path, label: str) -> None:
    """Export one RAM-monitor or battery run through fixed field allowlists; never overwrite."""
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,47}", label):
        raise ValueError("--label must be 2–48 lowercase letters, digits, or hyphens, starting with a letter/digit")
    run_dir = run_dir.expanduser().resolve(strict=True)
    if not run_dir.is_dir():
        raise ValueError("--run-dir must name an existing directory")
    battery_run = (run_dir / "battery-telemetry.csv").is_file()
    target = DEST / ("battery" if battery_run else "ram") / label
    if target.exists():
        raise FileExistsError("Destination already exists; choose a new label. No files were overwritten.")
    target.mkdir(parents=True)
    MANIFEST.clear(); MANIFEST.update({"schema_version": 1, "mode": "explicit-run-dir-export", "label": label,
                                      "generated_utc": None, "files": [], "excluded": [
        {"source_area": "supplied run directory", "reason": "fixed fields and filenames only; raw process lists, context files, identifiers, and all other files are ignored"}]})
    if battery_run:
        src = run_dir / "battery-telemetry.csv"
        columns = ["Timestamp", "BatteryStatusProvider", "PowerOnline", "Charging", "Discharging", "Critical",
                   "RemainingCapacityMWh", "ChargeRateMilliwatts", "DischargeRateMilliwatts",
                   "FullChargedCapacityProvider", "FullChargedCapacityMWh", "CycleCountProvider", "CycleCount",
                   "TemperatureProvider", "BatteryTemperatureRaw", "TemperatureUnits"]
        filtered_csv_path(src, "supplied-run/battery-telemetry.csv", target / "telemetry.csv", columns,
                          "fixed battery numeric/status/time columns only; error text and device identity omitted; blank temperature retained")
        summary_src = run_dir / "summary.json"
        if summary_src.is_file():
            obj = json.loads(summary_src.read_text(encoding="utf-8-sig"))
            safe = {k: obj[k] for k in ("Started", "Finished", "RequestedDurationSeconds", "SampleIntervalSeconds", "Samples",
                                         "FirstSample", "LastSample", "BatteryStatusProviderStates", "FullCapacityProviderStates",
                                         "TemperatureProviderStates", "NumericMetrics") if k in obj}
            register(summary_src, target / "summary.json", "allowlisted aggregate battery fields; context and identities omitted",
                     source_label="supplied-run/summary.json", payload=(json.dumps(safe, indent=2) + "\n").encode())
    else:
        system = run_dir / "system.txt"
        if system.is_file():
            hardware_summary_path(system, "supplied-run/system.txt", target / "hardware.json", "from supplied run metadata", "unspecified")
        machine = run_dir / "machine.json"
        if machine.is_file():
            obj = json.loads(machine.read_text(encoding="utf-8-sig"))
            cpu = [{k: x[k] for k in ("Name", "NumberOfCores", "NumberOfLogicalProcessors", "MaxClockSpeed") if k in x}
                   for x in obj.get("CPUs", []) if isinstance(x, dict)]
            modules = [{k: x[k] for k in ("PartNumber", "Capacity", "Speed", "ConfiguredClockSpeed") if k in x}
                       for x in obj.get("MemoryModules", []) if isinstance(x, dict)]
            osinfo = obj.get("OS", {})
            safe_hw = {"captured": obj.get("Captured"), "system_model": obj.get("ComputerModel"),
                       "os": {k: osinfo[k] for k in ("Caption", "Version", "BuildNumber", "Architecture") if k in osinfo},
                       "installed_physical_memory_bytes": obj.get("InstalledPhysicalMemoryBytes"),
                       "cpus": cpu, "memory_modules": modules,
                       "active_power_plan": re.sub(r"(?i)Power Scheme GUID:.*?\(([^)]+)\)", r"\1", str(obj.get("ActivePowerPlan", ""))),
                       "ac_line_status": obj.get("ACLineStatus"),
                       "scope": "Allowlisted CIM fields; computer name, battery details, serials and device locators omitted."}
            register(machine, target / "hardware.json", "allowlisted machine fields only; computer name, battery details, serials, and paths omitted",
                     source_label="supplied-run/machine.json", payload=(json.dumps(safe_hw, indent=2) + "\n").encode())
        telemetry = run_dir / "telemetry.csv"
        if telemetry.is_file():
            columns = ["timestamp", "available_mib", "committed_gib", "commit_limit_gib", "pages_input_per_s", "pages_output_per_s",
                       "page_reads_per_s", "page_faults_per_s", "cpu_total_pct", "cpu_core_max_pct", "disk_read_sec", "disk_write_sec", "disk_queue"]
            filtered_csv_path(telemetry, "supplied-run/telemetry.csv", target / "telemetry.csv", columns,
                              "allowlisted memory/CPU/disk counters only; local host paths absent")
        paging = run_dir / "paging-pressure.csv"
        if paging.is_file():
            filtered_csv_path(paging, "supplied-run/paging-pressure.csv", target / "paging-pressure.csv", ["Timestamp", "Path", "CookedValue"],
                              "memory counter structure retained; host name replaced by HOST")
        for name in ("process-groups-start.csv", "process-groups-end.csv"):
            src = run_dir / name
            if src.is_file():
                filtered_csv_path(src, f"supplied-run/{name}", target / name, ["Category", "ProcessCount", "WorkingSetMiB", "PrivateMemoryMiB"],
                                  "aggregate app categories only; PIDs, titles, and process names omitted")
        summary_src = run_dir / "summary.json"
        if summary_src.is_file():
            obj = json.loads(summary_src.read_text(encoding="utf-8-sig"))
            safe = {k: obj[k] for k in ("Started", "Finished", "RequestedDurationSeconds", "SampleIntervalSeconds", "Samples",
                                         "FirstSample", "LastSample", "Metrics", "SecondsBelow1GiBAvailable",
                                         "SecondsBelow2GiBAvailable", "SamplesPagesInputOver100PerSec",
                                         "SamplesPagesInputOver1000PerSec", "SamplesPagesOutputOver100PerSec") if k in obj}
            register(summary_src, target / "summary.json", "allowlisted timing, counter aggregates, and sample counts only",
                     source_label="supplied-run/summary.json", payload=(json.dumps(safe, indent=2) + "\n").encode())
    for folder in (run_dir, run_dir / "elevated", run_dir / "benchmarks"):
        if not folder.is_dir():
            continue
        for src in folder.iterdir():
            if not src.is_file():
                continue
            safe = re.fullmatch(r"(?:winsat-mem-[1-5]|mlc-(?:idle_latency|max_bandwidth|peak_injection_bandwidth|loaded_latency)-[1-5]|(?:idle_latency|max_bandwidth|peak_injection_bandwidth|loaded_latency)-[1-5])\.txt", src.name, re.I)
            if safe:
                copy = target / "benchmarks" / src.name
                register(src, copy, "sanitized allowlisted WinSAT/MLC text log; paths and identifiers redacted", source_label=f"supplied-run/{src.name}",
                         payload=clean_text(src.read_text(encoding="utf-8-sig", errors="replace")).encode("utf-8"))
            elif src.name == "run-status.jsonl":
                rows=[]
                for line in src.read_text(encoding="utf-8-sig").splitlines():
                    if line.strip():
                        obj=json.loads(line); rows.append({k: obj[k] for k in ("Name","Arguments","Started","Completed","ElapsedSeconds","ExitCode") if k in obj})
                register(src, target / "benchmarks" / src.name, "allowlisted status keys only; paths omitted", source_label="supplied-run/run-status.jsonl",
                         payload=("\n".join(json.dumps(x,separators=(",",":")) for x in rows)+"\n").encode())
            elif src.name == "run-info.json":
                obj=json.loads(src.read_text(encoding="utf-8-sig"))
                keep=("Started","Finished","RunDate","IsAdministrator","MlcVersion","MlcSignatureStatus","MlcSigner","MlcSha256",
                      "MlcTests","RepetitionsPerMlcTest","WinSATArguments","WinSATRepetitions","Scope","DriverAction","SystemChanges")
                safe={k:obj[k] for k in keep if k in obj}
                register(src, target / "benchmarks" / src.name, "allowlisted run metadata; local paths omitted", source_label="supplied-run/run-info.json",
                         payload=(json.dumps(safe,indent=2)+"\n").encode())
    if not MANIFEST["files"]:
        raise ValueError("No allowlisted files found in the supplied run directory")
    MANIFEST["generated_utc"] = datetime.now(timezone.utc).isoformat()
    scan = final_scan(DEST); MANIFEST["public_readiness_scan"] = scan
    if scan["violations"]:
        raise RuntimeError("Privacy scan found issue(s); inspect only the safe check/path labels in the manifest.")
    (target / "manifest.json").write_text(json.dumps(MANIFEST, indent=2, ensure_ascii=False)+"\n", encoding="utf-8")
    print(f"Wrote {len(MANIFEST['files'])} allowlisted files under {target.relative_to(ROOT).as_posix()}/; root manifest preserved")


def benchmark_set(label: str, source_root: str, dest_root: str, mlc_names: list[str], winsat_dir: str, current_prefix: str = "") -> None:
    src_root = ROOT / source_root
    for kind, names in (("mlc", mlc_names), ("winsat", [f"winsat-mem-{i}.txt" for i in range(1, 6)])):
        for name in names:
            src = src_root / (name if kind == "mlc" else f"{winsat_dir}/{name}")
            dst = DEST / dest_root / "benchmarks" / kind / name
            if src.exists():
                copy_text(rel(src), rel(dst), "sanitized copy of completed raw benchmark log; path/identifier patterns redacted")
    status = src_root / "elevated" / "run-status.jsonl"
    if status.exists():
        entries = []
        for line in status.read_text(encoding="utf-8-sig").splitlines():
            if line.strip():
                x = json.loads(line)
                entries.append({k: x[k] for k in ("Name", "Arguments", "Started", "Completed", "ElapsedSeconds", "ExitCode") if k in x})
        register(status, DEST / dest_root / "benchmarks" / "run-status.jsonl",
                 "allowlisted status fields only; executable/output paths omitted",
                 payload=("\n".join(json.dumps(x, separators=(",", ":")) for x in entries) + "\n").encode())
    info = src_root / "elevated" / "run-info.json"
    if info.exists():
        original = json.loads(info.read_text(encoding="utf-8-sig"))
        safe = {"run_date": original.get("RunDate"), "administrator": original.get("IsAdministrator"),
                "mlc_signature_status": original.get("MlcSignatureStatus"),
                "scope": original.get("Scope"), "driver_action": original.get("DriverAction"),
                "suite": label}
        register(info, DEST / dest_root / "benchmarks" / "run-info.json", "allowlisted metadata; local executable and destination paths omitted",
                 payload=(json.dumps(safe, indent=2) + "\n").encode())


